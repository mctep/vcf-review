/** Picks a synthetic variant set from the file name (demo convenience). */
export function variantSetForFile(fileName: string): VariantSetId {
  const n = fileName.toLowerCase()
  if (n.includes('mel')) return 'melanoma'
  if (n.includes('crc') || n.includes('colo')) return 'colorectal'
  if (n.includes('brca') || n.includes('breast')) return 'breast'
  return 'nsclc'
}
